public class case_convertion {
    public static void main(String[] args) {
        String name = "gautam";
        String upperCaseName = name.toUpperCase();
        System.out.println("to upper case: " + upperCaseName);
        String lowerCaseName = name.toLowerCase();
        System.out.println("to lower case: " + lowerCaseName);

    }
}